  window.getLang = function () {
    const saved = localStorage.getItem('site_lang');
    return saved === 'en' ? 'en' : 'bn';
  };

  window.t = function (key, vars = {}) {
    const lang = window.getLang();
    let str = (DICT[lang] && DICT[lang][key]) || DICT.bn[key] || key;
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
    return str;
  };

  window.localizeField = function (obj, field) {
    if (!obj) return '';
    if (window.getLang() === 'en' && obj[field + '_en']) {
      return obj[field + '_en'];
    }
    return obj[field] || '';
  };

  window.translateAttr = function (val) {
    if (!val) return '';
    if (window.getLang() === 'en') {
      return ATTR_MAP_EN[val] || val;
    }
    return val;
  };

  window.formatPrice = function (amount) {
    const num = parseFloat(amount || 0);
    const loc = window.getLang() === 'en' ? 'en-US' : 'bn-BD';
    return '৳' + num.toLocaleString(loc);
  };

  window.getDistrictList = function () {
    const lang = window.getLang();
    return DISTRICTS.map(([bn, en]) => ({ value: bn, label: lang === 'en' ? en : bn }));
  };

  window.renderLangSwitchers = function () {
    const lang = window.getLang();
    document.querySelectorAll('[data-lang-switcher]').forEach((el) => {
      el.innerHTML = `
        <div class="lang-switch" role="group" aria-label="Language Switcher">
          <button type="button" class="lang-btn ${lang === 'bn' ? 'active' : ''}" onclick="setLang('bn')">বাংলা</button>
          <button type="button" class="lang-btn ${lang === 'en' ? 'active' : ''}" onclick="setLang('en')">EN</button>
        </div>
      `;
    });
  };

  window.applyTranslations = function () {
    const lang = window.getLang();
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      el.textContent = window.t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', window.t(key));
    });
    window.renderLangSwitchers();
  };

  window.setLang = function (lang) {
    localStorage.setItem('site_lang', lang === 'en' ? 'en' : 'bn');
    window.applyTranslations();
    if (typeof window.onLanguageChange === 'function') {
      window.onLanguageChange(window.getLang());
    }
  };

  document.addEventListener('DOMContentLoaded', () => {
    window.applyTranslations();
  });
